// CHARACTER MANAGER (Roster Controller & Persistence)
// =============================================================
export class CharacterManager {
  constructor() {
    this.characters = CHARACTERS;
    this.currentIndex = 0;
    this.loadSaved();
  }

  loadSaved() {
    try {
      const saved = localStorage.getItem('celeste_char_id');
      if (saved) {
        const found = this.characters.findIndex(c => c.id === saved);
        if (found >= 0) this.currentIndex = found;
      }
    } catch (e) {}
  }

  save() {
    try {
      localStorage.setItem('celeste_char_id', this.characters[this.currentIndex].id);
    } catch (e) {}
  }

  getCurrent() {
    return this.characters[this.currentIndex];
  }

  getAll() {
    return this.characters;
  }

  select(id) {
    const idx = this.characters.findIndex(c => c.id === id);
    if (idx >= 0) {
      this.currentIndex = idx;
      this.save();
      return this.getCurrent();
    }
    return null;
  }

  setByIndex(idx) {
    if (idx >= 0 && idx < this.characters.length) {
      this.currentIndex = idx;
      this.save();
      return this.getCurrent();
    }
    return null;
  }

  next() {
    this.currentIndex = (this.currentIndex + 1) % this.characters.length;
    this.save();
    return this.getCurrent();
  }

  prev() {
    this.currentIndex = (this.currentIndex - 1 + this.characters.length) % this.characters.length;
    this.save();
    return this.getCurrent();
  }
}
