export class Level {
  constructor(roomIndex = 0) {
    this.currentRoomIndex = roomIndex;
    this.cols = 32;
    this.rows = 18;
    this.width = 320;
    this.height = 180;
    this.grid = [];
    this.collectibles = [];
    this.crystals = [];
    this.springs = [];
    this.crumblers = [];
    this.spikes = [];
    this.dreamBlocks = [];
    this.movingPlatforms = [];
    this.icicles = [];
    this.bumpers = [];
    this.feathers = [];
    this.beatTimer = 0;
    this.beatPhase = 0;
    this.heartPos = null;
    this.spawnX = 30;
    this.spawnY = 100;
    this.exitArea = null;
    this.flagPos = null;
    try {
      const savedBerries = localStorage.getItem('seleste_collected_berries');
      this.collectedBerries = savedBerries ? new Set(JSON.parse(savedBerries)) : new Set();
      this.collectedHeart = localStorage.getItem('seleste_collected_heart') === 'true';
    } catch (e) {
      this.collectedBerries = new Set();
      this.collectedHeart = false;
    }
    this.roomTitleTimer = 2.8;
    this.wind = 0;
    this.biome = 0;
    this.windParticles = [];

    this.initWindParticles();
    this.loadRoom(this.currentRoomIndex);
  }

  initWindParticles() {
    this.windParticles = [];
    const count = 45;
    const roomW = this.width || 640;
    const roomH = this.height || 360;
    for (let i = 0; i < count; i++) {
      this.windParticles.push({
        x: Math.random() * roomW,
        y: Math.random() * roomH,
        len: 8 + Math.random() * 16,
        speed: 120 + Math.random() * 100,
        alpha: 0.35 + Math.random() * 0.4
      });
    }
  }

  loadRoom(index) {
    this.isCustomPlaytest = false;
    this.currentRoomIndex = Math.max(0, Math.min(LEVEL_DATA.length - 1, index));
    const room = LEVEL_DATA[this.currentRoomIndex];

    this.name = room.name || `Room ${this.currentRoomIndex + 1}`;
    this.sub = room.sub || 'EXPEDITION';
    this.roomTitleTimer = 2.8;
    this.wind = room.wind || 0;
    this.biome = room.biome || 0;
    this.featherTime = (typeof room.featherTime === 'number' && room.featherTime > 0) ? room.featherTime : 2.5;

    this.rows = room.map.length;
    this.cols = room.map[0].length;
    this.width = this.cols * TILE_SIZE;
    this.height = this.rows * TILE_SIZE;
    this.initWindParticles();

    this.initRoomEntities(room);
  }

  loadCustomRoom(customRoom) {
    this.isCustomPlaytest = true;
    const room = customRoom;

    this.name = room.name || 'Custom Level';
    this.sub = room.sub || 'CUSTOM ASCENT';
    this.roomTitleTimer = 2.8;
    this.wind = room.wind || 0;
    this.biome = room.biome || 0;
    this.featherTime = (typeof room.featherTime === 'number' && room.featherTime > 0) ? room.featherTime : 2.5;

    this.rows = room.map.length;
    this.cols = room.map[0].length;
    this.width = this.cols * TILE_SIZE;
    this.height = this.rows * TILE_SIZE;
    this.initWindParticles();

    this.initRoomEntities(room);
  }

  initRoomEntities(room) {

    this.grid = [];
    this.collectibles = [];
    this.crystals = [];
    this.springs = [];
    this.crumblers = [];
    this.spikes = [];
    this.dreamBlocks = [];
    this.movingPlatforms = [];
    this.icicles = [];
    this.bumpers = [];
    this.feathers = [];
    this.beatTimer = 0;
    this.beatPhase = 0;
    this.heartPos = null;
    this.exitArea = null;
    this.flagPos = null;

    if (room.movingPlatforms) {
      room.movingPlatforms.forEach(mp => {
        this.movingPlatforms.push({
          x: mp.startX,
          y: mp.startY,
          startX: mp.startX,
          startY: mp.startY,
          endX: mp.endX,
          endY: mp.endY,
          w: mp.w,
          h: mp.h,
          speed: mp.speed,
          dir: 1,
          vx: 0,
          vy: 0
        });
      });
    }

    for (let r = 0; r < this.rows; r++) {
      const row = [];
      const line = room.map[r] || '';
      for (let c = 0; c < this.cols; c++) {
        const char = line[c] || ' ';
        const x = c * TILE_SIZE;
        const y = r * TILE_SIZE;

        if (char === '#') row.push(1);
        else if (char === 'M') row.push(3);
        else if (char === '1') row.push(4); // Rhythm Beat Block A
        else if (char === '2') row.push(5); // Rhythm Beat Block B
        else row.push(0);

        if (char === 'P') {
          // Spawn safely above floor
          this.spawnX = x + 1;
          this.spawnY = y - 2;
        } else if (char === 'E') {
          // Standard 12x16 pixel doorway sitting cleanly on the floor below
          this.exitArea = { x: x - 1, y: y - 6, w: 12, h: 16 };
        } else if (char === 'F') {
          this.flagPos = { x, y };
        } else if (char === 'H' && !this.collectedHeart) {
          this.heartPos = { x: x + 1, y: y + 1, baseY: y + 1, hover: 0, frame: 0, timer: 0 };
        } else if (char === 'G') {
          this.feathers.push({
            x,
            y,
            baseX: x,
            baseY: y,
            active: true,
            respawnTimer: 0,
            hoverTimer: Math.random() * Math.PI,
            animTimer: 0,
            animFrame: 0
          });
        } else if (char === 'B') {
          this.bumpers.push({
            x: x + 1,
            y: y + 1,
            pulseTimer: Math.random() * Math.PI * 2,
            squashTimer: 0,
            cooldown: 0
          });
        } else if (char === 'I') {
          this.icicles.push({
            x: x + 2,
            y,
            startY: y,
            state: 'idle',
            shakeTimer: 0,
            vy: 0,
            respawnTimer: 0
          });
        } else if (char === '*') {
          const berryId = `berry-${this.currentRoomIndex}-${c}-${r}`;
          if (!this.collectedBerries.has(berryId)) {
            this.collectibles.push({
              id: berryId,
              x: x + 1,
              y: y - 1,
              baseX: x + 1,
              baseY: y - 1,
              state: 'idle', // 'idle' or 'following'
              safeLandTimer: 0,
              hoverTimer: Math.random() * Math.PI,
              animFrame: 0,
              animTimer: 0
            });
          }
        } else if (char === 'D') {
          this.crystals.push({
            x: x - 1,
            y: y - 2,
            active: true,
            respawnTimer: 0,
            animFrame: 0,
            animTimer: 0
          });
        } else if (char === 'S') {
          this.springs.push({
            x,
            y,
            state: 'idle',
            timer: 0
          });
        } else if (char === 'C') {
          this.crumblers.push({
            x,
            y,
            w: TILE_SIZE,
            h: TILE_SIZE,
            active: true,
            shaking: false,
            shakeTimer: 0,
            respawnTimer: 0
          });
        } else if (char === '^') {
          this.spikes.push({ x, y, dir: 'up' });
        } else if (char === 'v') {
          this.spikes.push({ x, y, dir: 'down' });
        } else if (char === '<') {
          this.spikes.push({ x, y, dir: 'left' });
        } else if (char === '>') {
          this.spikes.push({ x, y, dir: 'right' });
        }
      }
      this.grid.push(row);
    }

    // Link spikes to their supporting crumble block (if attached to one)
    for (const spk of this.spikes) {
      let baseX = spk.x;
      let baseY = spk.y;
      if (spk.dir === 'up') baseY += TILE_SIZE;
      else if (spk.dir === 'down') baseY -= TILE_SIZE;
      else if (spk.dir === 'left') baseX += TILE_SIZE;
      else if (spk.dir === 'right') baseX -= TILE_SIZE;

      spk.attachedCrumbler = this.crumblers.find(cb => cb.x === baseX && cb.y === baseY) || null;
    }
  }

  isSolidTile(c, r, isDreamPhasing = false, isDashing = false) {
    // Outside level grid: open air and bottomless abyss (never solid blocks)
    // In Celeste, falling off an open border drops cleanly into the abyss to die
    if (r < 0 || r >= this.rows || c < 0 || c >= this.cols) return false;

    const tile = this.grid[r][c];
    if (tile === 1) return true;
    if (tile === 3) {
      if (isDreamPhasing || isDashing) return false;
      return true;
    }
    if (tile === 4) return this.beatPhase < 2; // Rhythm Block A
    if (tile === 5) return this.beatPhase >= 2; // Rhythm Block B
    return false;
  }

  isDreamBlockAt(px, py) {
    const c = Math.floor(px / TILE_SIZE);
    const r = Math.floor(py / TILE_SIZE);
    if (r >= 0 && r < this.rows && c >= 0 && c < this.cols) {
      return this.grid[r][c] === 3;
    }
    return false;
  }

  overlapsDreamBlock(px, py, pw, ph) {
    const left = Math.floor(px / TILE_SIZE);
    const right = Math.floor((px + pw - 1) / TILE_SIZE);
    const top = Math.floor(py / TILE_SIZE);
    const bottom = Math.floor((py + ph - 1) / TILE_SIZE);

    for (let r = top; r <= bottom; r++) {
      for (let c = left; c <= right; c++) {
        if (r >= 0 && r < this.rows && c >= 0 && c < this.cols) {
          if (this.grid[r][c] === 3) return true;
        }
      }
    }
    return false;
  }

  isMovingOrCrumblingSolid(px, py, pw, ph) {
    for (const cb of this.crumblers) {
      if (cb.active && px + pw > cb.x && px < cb.x + cb.w && py + ph > cb.y && py < cb.y + cb.h) {
        return true;
      }
    }
    for (const mp of this.movingPlatforms) {
      if (px + pw > mp.x && px < mp.x + mp.w && py + ph > mp.y && py < mp.y + mp.h) {
        return true;
      }
    }
    return false;
  }

  update(dt, player, particleSystem, screenShake, onNextRoom, onVictory, onFreeze, onHaptic = null) {
    if (this.roomTitleTimer > 0) this.roomTitleTimer -= dt;

    // Wind particles
    if (this.wind !== 0) {
      const dir = this.wind > 0 ? 1 : -1;
      const speedMult = Math.max(1, Math.abs(this.wind) / 12);
      for (const wp of this.windParticles) {
        wp.x += dir * wp.speed * speedMult * dt;
        if (dir > 0 && wp.x > this.width + 25) {
          wp.x = -25;
          wp.y = Math.random() * this.height;
        } else if (dir < 0 && wp.x < -25) {
          wp.x = this.width + 25;
          wp.y = Math.random() * this.height;
        }
      }
    }

    // Moving Platforms
    for (const mp of this.movingPlatforms) {
      const targetX = mp.dir === 1 ? mp.endX : mp.startX;
      const targetY = mp.dir === 1 ? mp.endY : mp.startY;
      const dx = targetX - mp.x;
      const dy = targetY - mp.y;
      const dist = Math.hypot(dx, dy);

      if (dist < 2) {
        mp.dir = -mp.dir;
        mp.vx = 0;
        mp.vy = 0;
      } else {
        mp.vx = (dx / dist) * mp.speed;
        mp.vy = (dy / dist) * mp.speed;
        mp.x += mp.vx * dt;
        mp.y += mp.vy * dt;

        // Player standing on platform
        if (
          !player.dead &&
          player.x + player.width > mp.x &&
          player.x < mp.x + mp.w &&
          Math.abs(player.y + player.height - mp.y) < 3 &&
          player.vy >= 0
        ) {
          player.x += mp.vx * dt;
          player.y = mp.y - player.height;
          player.onGround = true;
        }
      }
    }

    // Falling Icicles
    for (const ic of this.icicles) {
      if (ic.state === 'idle') {
        if (
          !player.dead &&
          Math.abs(player.x + player.width / 2 - (ic.x + 3)) < 12 &&
          player.y > ic.y &&
          player.y < ic.y + 120
        ) {
          ic.state = 'shaking';
          ic.shakeTimer = 0.22;
        }
      } else if (ic.state === 'shaking') {
        ic.shakeTimer -= dt;
        if (Math.random() < 0.3) {
          particleSystem.emit(ic.x + 3, ic.y + 8, 0, 10, 4, 0.15, 1);
        }
        if (ic.shakeTimer <= 0) {
          ic.state = 'falling';
          ic.vy = 65;
        }
      } else if (ic.state === 'falling') {
        ic.vy += 650 * dt;
        ic.y += ic.vy * dt;

        // Player hit
        if (
          !player.dead &&
          player.x + player.width > ic.x &&
          player.x < ic.x + 6 &&
          player.y + player.height > ic.y &&
          player.y < ic.y + 10
        ) {
          player.kill(particleSystem, screenShake, onFreeze);
          ic.state = 'dead';
          ic.respawnTimer = 2.5;
        }

        // Solid hit or fell into the abyss
        const c = Math.floor((ic.x + 3) / TILE_SIZE);
        const r = Math.floor((ic.y + 10) / TILE_SIZE);
        if (this.isSolidTile(c, r) || ic.y > this.height + 20) {
          ic.state = 'dead';
          ic.respawnTimer = 2.5;
          particleSystem.emitDustPuff(ic.x + 3, Math.min(this.height - 2, ic.y + 10), 4, 0, 4);
        }
      } else if (ic.state === 'dead') {
        ic.respawnTimer -= dt;
        if (ic.respawnTimer <= 0) {
          ic.state = 'idle';
          ic.y = ic.startY;
          ic.vy = 0;
        }
      }
    }

    // Core Bumper Orbs
    for (const bmp of this.bumpers) {
      bmp.pulseTimer += dt * 5;
      if (bmp.squashTimer > 0) bmp.squashTimer -= dt;
      if (bmp.cooldown > 0) bmp.cooldown -= dt;

      if (!player.dead && bmp.cooldown <= 0) {
        const pCenterX = player.x + player.width / 2;
        const pCenterY = player.y + player.height / 2;
        const bCenterX = bmp.x + 4;
        const bCenterY = bmp.y + 4;
        const dx = pCenterX - bCenterX;
        const dy = pCenterY - bCenterY;
        const dist = Math.hypot(dx, dy);

        if (dist < 11) {
          bmp.cooldown = 0.22;
          bmp.squashTimer = 0.25;
          const normX = dist > 0.01 ? (dx / dist) : 0;
          let normY = dist > 0.01 ? (dy / dist) : -1;

          if (normY > -0.35) normY = -0.65;
          const bounceLen = Math.hypot(normX, normY);

          player.vx = (normX / bounceLen) * 320;
          player.vy = (normY / bounceLen) * 330;
          player.isDashing = false;
          player.refillDash(particleSystem);
          player.onGround = false;
          player.jumpBufferTimer = 0;
          player.coyoteTimer = 0;
          player.scaleX = 0.55;
          player.scaleY = 1.6;

          sfx.playSpring();
          if (onHaptic) onHaptic('spring');
          screenShake.add(3.5);
          if (onFreeze) onFreeze(0.04);
          particleSystem.addShockwave(bCenterX, bCenterY, 8);
          for (let i = 0; i < 10; i++) {
            particleSystem.emit(
              bCenterX, bCenterY,
              (Math.random() - 0.5) * 70, (Math.random() - 0.5) * 70,
              8, 0.4, 2
            );
          }
        }
      }
    }

    // Springs
    for (const sp of this.springs) {
      if (sp.state !== 'idle') {
        sp.timer -= dt;
        if (sp.timer <= 0) sp.state = 'idle';
      }

      if (!player.dead) {
        const touchSpring =
          player.x + player.width > sp.x - 2 &&
          player.x < sp.x + TILE_SIZE + 2 &&
          player.y + player.height >= sp.y &&
          player.y + player.height <= sp.y + TILE_SIZE + 4 &&
          player.vy >= -30;

        if (touchSpring) {
          sp.state = 'up';
          sp.timer = 0.3;
          player.y = sp.y - player.height + 1; // Snap cleanly to top of spring pad
          player.vy = -340;
          player.springBounceTimer = 0.22; // Allows Super Spring Jump boost and protects velocity from jump release cut
          player.isDashing = false;
          player.onGround = false;
          player.coyoteTimer = 0;
          player.refillDash(particleSystem);
          player.scaleX = 0.55;
          player.scaleY = 1.65;
          sfx.playSpring();
          if (onHaptic) onHaptic('spring');
          screenShake.add(2.5);
          if (onFreeze) onFreeze(0.03);
          particleSystem.emitDustPuff(sp.x + TILE_SIZE / 2, sp.y + 4, 7, 0, 8);
          particleSystem.addShockwave(sp.x + TILE_SIZE / 2, sp.y + 4, 8);
        }
      }
    }

    // Dash Crystals
    for (const crys of this.crystals) {
      if (!crys.active) {
        crys.respawnTimer -= dt;
        if (crys.respawnTimer <= 0) {
          crys.active = true;
          particleSystem.emit(crys.x + 6, crys.y + 7, 0, -15, 8, 0.3, 2);
        }
      } else {
        crys.animTimer += dt;
        if (crys.animTimer > 0.14) {
          crys.animTimer = 0;
          crys.animFrame = (crys.animFrame + 1) % SPRITES.crystal.length;
        }

        if (
          !player.dead &&
          !player.dashAvailable &&
          player.x + player.width > crys.x &&
          player.x < crys.x + 12 &&
          player.y + player.height > crys.y &&
          player.y < crys.y + 14
        ) {
          crys.active = false;
          crys.respawnTimer = 2.4;
          player.refillDash(particleSystem);
          sfx.playCrystalRefill();
          screenShake.add(2.5);
          if (onFreeze) onFreeze(0.03);
          particleSystem.addShockwave(crys.x + 6, crys.y + 7, 8);
        }
      }
    }

    // Crumbling Blocks
    for (const cb of this.crumblers) {
      if (!cb.active) {
        cb.respawnTimer -= dt;
        if (cb.respawnTimer <= 0) {
          cb.active = true;
          cb.shaking = false;
        }
      } else if (cb.shaking) {
        cb.shakeTimer -= dt;
        if (Math.random() < 0.3) {
          particleSystem.emit(cb.x + Math.random() * cb.w, cb.y + cb.h, 0, 15, 3, 0.2, 1);
        }
        if (cb.shakeTimer <= 0) {
          cb.active = false;
          cb.shaking = false;
          cb.respawnTimer = 2.2;
          particleSystem.emitDustPuff(cb.x + cb.w / 2, cb.y + cb.h / 2, 5, 0, 4);
        }
      } else if (!player.dead) {
        if (
          player.x + player.width > cb.x &&
          player.x < cb.x + cb.w &&
          Math.abs(player.y + player.height - cb.y) < 2 &&
          player.onGround
        ) {
          cb.shaking = true;
          cb.shakeTimer = 0.38;
        }
      }
    }

    // Secret Crystal Heart
    if (this.heartPos && !this.collectedHeart) {
      this.heartPos.hover += dt * 3;
      this.heartPos.y = this.heartPos.baseY + Math.sin(this.heartPos.hover) * 3;
      this.heartPos.timer += dt;
      if (this.heartPos.timer > 0.2) {
        this.heartPos.timer = 0;
        this.heartPos.frame = (this.heartPos.frame + 1) % SPRITES.heart.length;
      }

      if (
        !player.dead &&
        player.x + player.width > this.heartPos.x &&
        player.x < this.heartPos.x + 12 &&
        player.y + player.height > this.heartPos.y &&
        player.y < this.heartPos.y + 12
      ) {
        this.collectedHeart = true;
        try {
          localStorage.setItem('seleste_collected_heart', 'true');
        } catch (e) {}
        sfx.playHeartCollect();
        if (onHaptic) onHaptic('heart');
        screenShake.add(4);
        if (onFreeze) onFreeze(0.08);
        for (let i = 0; i < 20; i++) {
          particleSystem.emit(
            this.heartPos.x + 5, this.heartPos.y + 5,
            (Math.random() - 0.5) * 80, (Math.random() - 0.5) * 80,
            8, 0.6, 2
          );
        }
      }
    }

    // Rhythm Beat Clock (125 BPM quarter note = 0.48s)
    this.beatTimer += dt;
    if (this.beatTimer >= 0.48) {
      this.beatTimer -= 0.48;
      this.beatPhase = (this.beatPhase + 1) % 4;
      const isHigh = (this.beatPhase === 0 || this.beatPhase === 2);
      sfx.playBeatTick(isHigh);
    }

    // Strawberries (#5 Trailing Companion with Safe Landing)
    for (let i = this.collectibles.length - 1; i >= 0; i--) {
      const berry = this.collectibles[i];
      berry.animTimer += dt;
      if (berry.animTimer > 0.12) {
        berry.animTimer = 0;
        berry.animFrame = (berry.animFrame + 1) % SPRITES.strawberry.length;
      }

      if (berry.state === 'idle') {
        berry.hoverTimer += dt * 3.5;
        berry.y = berry.baseY + Math.sin(berry.hoverTimer) * 2;
        berry.x = berry.baseX;

        // Player touches floating berry -> starts trailing behind!
        if (
          !player.dead &&
          player.x + player.width > berry.x &&
          player.x < berry.x + 10 &&
          player.y + player.height > berry.y &&
          player.y < berry.y + 12
        ) {
          berry.state = 'following';
          berry.safeLandTimer = 0;
          for (let p = 0; p < 8; p++) {
            particleSystem.emit(berry.x + 5, berry.y + 5, (Math.random() - 0.5) * 40, (Math.random() - 0.5) * 40, 7, 0.25, 2);
          }
          sfx.playBerryCollect();
        }
      } else if (berry.state === 'following') {
        if (player.dead) {
          // Madeline died! Strawberry snaps back home with dust poof
          berry.state = 'idle';
          berry.x = berry.baseX;
          berry.y = berry.baseY;
          berry.safeLandTimer = 0;
          particleSystem.emitDustPuff(berry.baseX + 5, berry.baseY + 5, 5, 0, 4);
        } else {
          // Spring follow physics behind player
          const targetX = player.x + (player.facing > 0 ? -11 : 15);
          const targetY = player.y - 5 + Math.sin(performance.now() * 0.006) * 3;
          berry.x += (targetX - berry.x) * Math.min(1.0, 13 * dt);
          berry.y += (targetY - berry.y) * Math.min(1.0, 13 * dt);

          // Safe Landing detection (player on ground, not sliding/dashing for 0.40s)
          if (player.onGround && !player.isDashing && !player.isWallSliding && Math.abs(player.vx) < 140) {
            berry.safeLandTimer += dt;
            if (berry.safeLandTimer >= 0.40) {
              // Cashed in!
              this.collectedBerries.add(berry.id);
              if (!this.isCustomPlaytest) {
                try {
                  localStorage.setItem('seleste_collected_berries', JSON.stringify(Array.from(this.collectedBerries)));
                } catch (e) {}
              }
              this.collectibles.splice(i, 1);
              sfx.playBerryCollect();
              if (onHaptic) onHaptic('berry');
              screenShake.add(2.5);
              if (onFreeze) onFreeze(0.05);
              particleSystem.emitBerryCollect(berry.x + 5, berry.y + 5);
            }
          } else {
            berry.safeLandTimer = 0;
          }
        }
      }
    }

    // Golden Feathers (360 DEG Free Flight)
    for (const ftr of this.feathers) {
      if (!ftr.active) {
        ftr.respawnTimer -= dt;
        if (ftr.respawnTimer <= 0) {
          ftr.active = true;
          particleSystem.emit(ftr.x + 5, ftr.y + 5, 0, -10, 8, 0.3, 2);
        }
      } else {
        ftr.hoverTimer += dt * 3.2;
        ftr.y = ftr.baseY + Math.sin(ftr.hoverTimer) * 2;
        ftr.animTimer += dt;
        if (ftr.animTimer > 0.15) {
          ftr.animTimer = 0;
          ftr.animFrame = (ftr.animFrame + 1) % SPRITES.feather.length;
        }

        if (
          !player.dead &&
          player.x + player.width > ftr.x - 1 &&
          player.x < ftr.x + 11 &&
          player.y + player.height > ftr.y - 1 &&
          player.y < ftr.y + 11
        ) {
          ftr.active = false;
          ftr.respawnTimer = 3.5;
          player.startFeatherFlight(particleSystem, this.featherTime);
          sfx.playFeatherCollect();
          if (onHaptic) onHaptic('feather');
          screenShake.add(3);
          if (onFreeze) onFreeze(0.05);
          particleSystem.addShockwave(ftr.x + 5, ftr.y + 5, 10);
          particleSystem.addFloater('FEATHER FLIGHT!', ftr.x - 20, ftr.y - 10, 8);
        }
      }
    }

    // Spikes (Fair, generous hitbox margins!)
    if (!player.dead) {
      for (const spk of this.spikes) {
        // Disappear with attached crumble block
        if (spk.attachedCrumbler && !spk.attachedCrumbler.active) continue;

        let hit = false;
        const px = player.x;
        const py = player.y;
        const pw = player.width;
        const ph = player.height;

        if (spk.dir === 'up') {
          if (px + pw > spk.x + 2 && px < spk.x + 8 && py + ph > spk.y + 4 && py < spk.y + 10) hit = true;
        } else if (spk.dir === 'down') {
          if (px + pw > spk.x + 2 && px < spk.x + 8 && py < spk.y + 6 && py + ph > spk.y) hit = true;
        } else if (spk.dir === 'left') {
          if (px + pw > spk.x + 4 && px < spk.x + 10 && py + ph > spk.y + 2 && py < spk.y + 8) hit = true;
        } else if (spk.dir === 'right') {
          if (px < spk.x + 6 && px + pw > spk.x && py + ph > spk.y + 2 && py < spk.y + 8) hit = true;
        }
        if (hit) {
          player.kill(particleSystem, screenShake, onFreeze);
          break;
        }
      }
    }

    // Abyss Fall Death (Falling into bottom abyss or off-screen cleanly respawns player like in Celeste)
    if (!player.dead && (player.y > this.height + 4 || player.x < -20 || player.x > this.width + 20)) {
      const deathBurstX = Math.max(8, Math.min(this.width - 8, player.x + player.width / 2));
      const deathBurstY = Math.min(this.height - 2, player.y + player.height / 2);
      player.kill(particleSystem, screenShake, onFreeze);
      particleSystem.emitDeathBurst(deathBurstX, deathBurstY);
    }

    // Summit Campfire Floating Embers
    if (this.flagPos && particleSystem && Math.random() < 0.45) {
      let floorY = this.flagPos.y + 10;
      const tileC = Math.floor(this.flagPos.x / TILE_SIZE);
      const tileR = Math.floor(this.flagPos.y / TILE_SIZE);
      for (let r = tileR + 1; r < this.rows; r++) {
        if (this.isSolidTile(tileC, r)) {
          floorY = r * TILE_SIZE;
          break;
        }
      }
      const emberX = this.flagPos.x - 9 + 2 + Math.random() * 6;
      const emberY = floorY - 5;
      const emberVx = (Math.random() - 0.5) * 8 + (this.wind * 0.15);
      const emberVy = -16 - Math.random() * 24;
      const emberCol = Math.random() > 0.6 ? 7 : (Math.random() > 0.3 ? 8 : 6);
      particleSystem.emit(emberX, emberY, emberVx, emberVy, emberCol, 0.4 + Math.random() * 0.35, 1, 15);
    }

    // Exit & Victory (Strict doorway entry, eliminates accidental continuation!)
    if (!player.dead) {
      if (this.flagPos && Math.hypot(player.x - this.flagPos.x, player.y - this.flagPos.y) < 20) {
        onVictory();
      } else if (this.exitArea) {
        const pCenterX = player.x + player.width / 2;
        const pCenterY = player.y + player.height / 2;
        const inDoor =
          pCenterX >= this.exitArea.x + 2 &&
          pCenterX <= this.exitArea.x + this.exitArea.w - 2 &&
          pCenterY >= this.exitArea.y &&
          pCenterY <= this.exitArea.y + this.exitArea.h + 2;

        if (inDoor) {
          sfx.playWarp();
          onNextRoom();
        }
      }
    }
  }

  render(ctx, palette) {
    const p = palette;
    // 0. Ambient Scaffolding & Background Wall Depth
    ctx.save();
    ctx.fillStyle = p.getColor(1);
    ctx.globalAlpha = 0.30;
    for (let r = 0; r < this.rows; r++) {
      for (let c = 0; c < this.cols; c++) {
        if (this.grid[r][c] === 0) {
          const nearSolid =
            (r > 0 && this.grid[r - 1][c] === 1) ||
            (r < this.rows - 1 && this.grid[r + 1][c] === 1) ||
            (c > 0 && this.grid[r][c - 1] === 1) ||
            (c < this.cols - 1 && this.grid[r][c + 1] === 1);
          if (nearSolid && (c + r) % 2 === 0) {
            ctx.fillRect(c * TILE_SIZE + 2, r * TILE_SIZE + 2, 6, 6);
          }
        }
      }
    }
    ctx.restore();

    // 0.5. Moving Platforms (Under solids & spikes so lifts clip under walls and blocks)
    for (const mp of this.movingPlatforms) {
      const x = Math.round(mp.x);
      const y = Math.round(mp.y);

      // Track Guide Rail (supports horizontal, vertical, and diagonal travel smoothly)
      ctx.save();
      ctx.strokeStyle = p.getColor(1);
      ctx.lineWidth = 1;
      ctx.beginPath();
      ctx.moveTo(Math.round(mp.startX + mp.w / 2) + 0.5, Math.round(mp.startY + mp.h / 2) + 0.5);
      ctx.lineTo(Math.round(mp.endX + mp.w / 2) + 0.5, Math.round(mp.endY + mp.h / 2) + 0.5);
      ctx.stroke();
      ctx.restore();

      // Platform body
      ctx.fillStyle = p.getColor(4);
      ctx.fillRect(x, y, mp.w, mp.h);
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(x, y, mp.w, 1);
      ctx.fillStyle = '#000000';
      ctx.fillRect(x, y + mp.h - 1, mp.w, 1);
    }

    // 1. Handcrafted Autotiled Solids & Celestial Dream Blocks
    for (let r = 0; r < this.rows; r++) {
      for (let c = 0; c < this.cols; c++) {
        const val = this.grid[r][c];
        const x = c * TILE_SIZE;
        const y = r * TILE_SIZE;

        if (val === 1) {
          const topAir = r === 0 || this.grid[r - 1][c] !== 1;
          const bottomAir = r === this.rows - 1 || this.grid[r + 1][c] !== 1;
          const leftAir = c === 0 || this.grid[r][c - 1] !== 1;
          const rightAir = c === this.cols - 1 || this.grid[r][c + 1] !== 1;

          // Main stone / masonry body
          ctx.fillStyle = p.getColor(2);
          ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);

          // Authentic brick mortar seams
          ctx.fillStyle = p.getColor(1);
          ctx.fillRect(x, y + 4, TILE_SIZE, 1);
          if ((r % 2 === 0 && c % 2 === 0) || (r % 2 !== 0 && c % 2 !== 0)) {
            ctx.fillRect(x + 5, y, 1, 4);
          } else {
            ctx.fillRect(x + 8, y + 5, 1, 4);
          }

          // Subtle stone bevel highlight
          ctx.fillStyle = p.getColor(3);
          ctx.fillRect(x + 1, y + 1, 2, 2);

          // Top surface trim based on Biome
          if (topAir) {
            let topColor = p.getColor(5); // Default moss / cyber conduit
            if (this.biome === 1) topColor = p.getColor(6); // Velvet / gold trim
            else if (this.biome === 2) topColor = '#ffffff'; // Alpine snow cap
            else if (this.biome === 3) topColor = '#ffffff'; // Summit crystal snow
            else if (this.biome === 4) topColor = p.getColor(6); // Mirror Temple rune trim
            else if (this.biome === 5) topColor = p.getColor(5); // Chasm bioluminescent crystal rim
            else if (this.biome === 6) topColor = p.getColor(7); // Molten magma ember trim
            else if (this.biome === 7) topColor = '#ffffff'; // Stratosphere celestial frost

            ctx.fillStyle = topColor;
            ctx.fillRect(x, y, TILE_SIZE, 2);

            // 1px bright specular line
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(x + 1, y, TILE_SIZE - 2, 1);

            // Organic hanging blades / snow overhangs
            if ((c * 3 + r) % 3 === 0) {
              ctx.fillStyle = topColor;
              ctx.fillRect(x + 2, y + 2, 2, 1);
            }
          }

          // Left edge highlight
          if (leftAir) {
            ctx.fillStyle = p.getColor(4);
            ctx.fillRect(x, y + (topAir ? 1 : 0), 1, TILE_SIZE - (topAir ? 1 : 0));
          }

          // Right edge shadow
          if (rightAir) {
            ctx.fillStyle = p.getColor(0);
            ctx.fillRect(x + TILE_SIZE - 1, y, 1, TILE_SIZE);
          }

          // Bottom edge shadow / stalactites
          if (bottomAir) {
            ctx.fillStyle = '#000000';
            ctx.fillRect(x, y + TILE_SIZE - 2, TILE_SIZE, 2);
            if ((c * 5 + r) % 4 === 0) {
              ctx.fillRect(x + 3, y + TILE_SIZE, 2, 2);
            }
          }
        } else if (val === 3) {
          // Dream Block: pure black celestial void + animated swirling stars
          ctx.fillStyle = '#000000';
          ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);

          const t = performance.now() * 0.003;
          if ((c * 7 + r * 13) % 4 === 0) {
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(x + 3, y + 3, 1, 1);
          }
          if ((c * 11 + r * 5) % 3 === 0) {
            ctx.fillStyle = p.getColor(7);
            ctx.fillRect(x + 6, y + 6, 1, 1);
          }
          if ((c * 17 + r * 19) % 5 === 0) {
            ctx.fillStyle = p.getColor(6);
            ctx.fillRect(x + 2, y + 7, 1, 1);
          }

          // Shimmering outer edge border
          ctx.strokeStyle = Math.sin(t * 3 + c * 0.5 + r * 0.5) > 0 ? '#ffffff' : p.getColor(5);
          ctx.lineWidth = 1;
          ctx.strokeRect(x + 0.5, y + 0.5, TILE_SIZE - 1, TILE_SIZE - 1);
        } else if (val === 4) {
          // Beat Block A: Solid during phase 0 & 1, Inactive during phase 2 & 3
          const isActive = this.beatPhase < 2;
          if (isActive) {
            ctx.fillStyle = p.getColor(7); // Neon magenta/coral
            ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(x + 1, y + 1, TILE_SIZE - 2, 1);
            ctx.fillRect(x + 1, y + 1, 1, TILE_SIZE - 2);
            ctx.fillStyle = p.getColor(1);
            ctx.fillRect(x, y + TILE_SIZE - 1, TILE_SIZE, 1);
            // Pulsing diamond core
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(x + 4, y + 3, 2, 4);
            ctx.fillRect(x + 3, y + 4, 4, 2);
          } else {
            ctx.save();
            ctx.strokeStyle = p.getColor(7);
            ctx.globalAlpha = 0.35;
            ctx.strokeRect(x + 0.5, y + 0.5, TILE_SIZE - 1, TILE_SIZE - 1);
            ctx.fillStyle = p.getColor(7);
            ctx.fillRect(x + 4, y + 4, 2, 2);
            ctx.restore();
          }
        } else if (val === 5) {
          // Beat Block B: Solid during phase 2 & 3, Inactive during phase 0 & 1
          const isActive = this.beatPhase >= 2;
          if (isActive) {
            ctx.fillStyle = p.getColor(5); // Neon cyan/teal
            ctx.fillRect(x, y, TILE_SIZE, TILE_SIZE);
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(x + 1, y + 1, TILE_SIZE - 2, 1);
            ctx.fillRect(x + 1, y + 1, 1, TILE_SIZE - 2);
            ctx.fillStyle = p.getColor(1);
            ctx.fillRect(x, y + TILE_SIZE - 1, TILE_SIZE, 1);
            // Pulsing diamond core
            ctx.fillStyle = '#ffffff';
            ctx.fillRect(x + 4, y + 3, 2, 4);
            ctx.fillRect(x + 3, y + 4, 4, 2);
          } else {
            ctx.save();
            ctx.strokeStyle = p.getColor(5);
            ctx.globalAlpha = 0.35;
            ctx.strokeRect(x + 0.5, y + 0.5, TILE_SIZE - 1, TILE_SIZE - 1);
            ctx.fillStyle = p.getColor(5);
            ctx.fillRect(x + 4, y + 4, 2, 2);
            ctx.restore();
          }
        }
      }
    }

    // 3. Crumbling Blocks
    for (const cb of this.crumblers) {
      if (cb.active) {
        const ox = cb.shaking ? (Math.random() * 2 - 1) : 0;
        const oy = cb.shaking ? (Math.random() * 2 - 1) : 0;
        const x = Math.round(cb.x + ox);
        const y = Math.round(cb.y + oy);

        ctx.fillStyle = p.getColor(3);
        ctx.fillRect(x, y, cb.w, cb.h);
        ctx.fillStyle = p.getColor(4);
        ctx.fillRect(x, y, cb.w, 1);
        ctx.fillStyle = p.getColor(2);
        ctx.fillRect(x + 2, y + 3, 3, 1);
        ctx.fillRect(x + 4, y + 4, 1, 3);
      }
    }

    // 4. Falling Icicles
    for (const ic of this.icicles) {
      if (ic.state !== 'dead') {
        const ox = ic.state === 'shaking' ? (Math.random() * 2 - 1) : 0;
        drawSprite(ctx, SPRITES.icicle, ic.x + ox, ic.y, palette);
      }
    }

    // 5. Spikes
    for (const spk of this.spikes) {
      // Disappear with attached crumble block
      if (spk.attachedCrumbler && !spk.attachedCrumbler.active) continue;

      const ox = (spk.attachedCrumbler && spk.attachedCrumbler.shaking) ? (Math.random() * 2 - 1) : 0;
      const oy = (spk.attachedCrumbler && spk.attachedCrumbler.shaking) ? (Math.random() * 2 - 1) : 0;

      const sprite = SPRITES.spikes[spk.dir];
      if (sprite) {
        drawSprite(ctx, sprite, Math.round(spk.x + 1 + ox), Math.round(spk.y + 1 + oy), palette);
      }
    }

    // 5.5 Core Bumper Orbs
    for (const bmp of this.bumpers) {
      const bx = Math.round(bmp.x);
      const by = Math.round(bmp.y + Math.sin(bmp.pulseTimer) * 1.5);
      const isSquashed = bmp.squashTimer > 0;
      const radius = isSquashed ? 6 : 5;

      ctx.save();
      // Outer glowing aura
      ctx.fillStyle = isSquashed ? '#ffffff' : p.getColor(7);
      ctx.beginPath();
      ctx.arc(bx + 4, by + 4, radius, 0, Math.PI * 2);
      ctx.fill();

      // Inner fiery/cosmic core rim
      ctx.fillStyle = isSquashed ? p.getColor(8) : p.getColor(5);
      ctx.beginPath();
      ctx.arc(bx + 4, by + 4, radius - 1.5, 0, Math.PI * 2);
      ctx.fill();

      // Sparkling star center
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(bx + 3, by + 3, 2, 2);
      ctx.restore();
    }

    // 6. Springs (Flush with ground surface)
    for (const sp of this.springs) {
      if (sp.state === 'up') {
        drawSprite(ctx, SPRITES.spring.up, sp.x - 1, sp.y + 2, palette);
      } else {
        drawSprite(ctx, SPRITES.spring.idle, sp.x - 1, sp.y + 4, palette);
      }
    }

    // 7. Dash Crystals
    for (const crys of this.crystals) {
      if (crys.active) {
        const spr = SPRITES.crystal[crys.animFrame % SPRITES.crystal.length];
        drawSprite(ctx, spr, crys.x, crys.y, palette);
      } else {
        ctx.save();
        ctx.strokeStyle = p.getColor(2);
        ctx.strokeRect(crys.x + 3, crys.y + 3, 6, 8);
        ctx.restore();
      }
    }

    // 8. Strawberries (#5 Trailing Companion with Safe Landing)
    for (const berry of this.collectibles) {
      const spr = SPRITES.strawberry[berry.animFrame % SPRITES.strawberry.length];
      if (berry.state === 'following') {
        // Trailing tether spark trail
        ctx.save();
        ctx.fillStyle = p.getColor(7);
        ctx.globalAlpha = 0.6;
        ctx.fillRect(Math.round(berry.x + 4), Math.round(berry.y + 11), 2, 2);
        ctx.fillRect(Math.round(berry.x + 3), Math.round(berry.y + 14), 1, 1);
        ctx.restore();

        // Safe landing charging ring indicator
        if (berry.safeLandTimer > 0) {
          ctx.save();
          ctx.strokeStyle = '#ffffff';
          ctx.lineWidth = 1;
          const prog = Math.min(1.0, berry.safeLandTimer / 0.40);
          ctx.beginPath();
          ctx.arc(Math.round(berry.x + 5), Math.round(berry.y - 3), 3, 0, Math.PI * 2 * prog);
          ctx.stroke();
          ctx.restore();
        }
      }
      drawSprite(ctx, spr, Math.round(berry.x), Math.round(berry.y), palette);
    }

    // 8.6 Golden Feathers (360 DEG Free Flight)
    for (const ftr of this.feathers) {
      if (ftr.active) {
        const spr = SPRITES.feather[ftr.animFrame % SPRITES.feather.length];
        const fx = Math.round(ftr.x);
        const fy = Math.round(ftr.y);

        // Glowing golden aura
        ctx.save();
        ctx.fillStyle = '#ffffff';
        ctx.globalAlpha = 0.35 + Math.sin(ftr.hoverTimer * 2) * 0.15;
        ctx.beginPath();
        ctx.arc(fx + 5, fy + 5, 7, 0, Math.PI * 2);
        ctx.fill();
        ctx.restore();

        drawSprite(ctx, spr, fx, fy, palette);
      } else {
        // Faded respawn placeholder
        ctx.save();
        ctx.strokeStyle = p.getColor(2);
        ctx.globalAlpha = 0.5;
        ctx.strokeRect(Math.round(ftr.x) + 2, Math.round(ftr.y) + 2, 6, 6);
        ctx.restore();
      }
    }

    // 9. Secret Crystal Heart
    if (this.heartPos && !this.collectedHeart) {
      const spr = SPRITES.heart[this.heartPos.frame % SPRITES.heart.length];
      drawSprite(ctx, spr, this.heartPos.x, this.heartPos.y, palette);
    }

    // 10. Summit Flag & Campfire (Grounded, animated with warm radial glow)
    if (this.flagPos) {
      // Find floor level underneath flagPos
      let floorY = this.flagPos.y + 10;
      const tileC = Math.floor(this.flagPos.x / TILE_SIZE);
      const tileR = Math.floor(this.flagPos.y / TILE_SIZE);
      for (let r = tileR + 1; r < this.rows; r++) {
        if (this.isSolidTile(tileC, r)) {
          floorY = r * TILE_SIZE;
          break;
        }
      }

      // Flag sprite is 12px wide, 10px tall (bottom line is stone base 2222)
      const flagX = this.flagPos.x;
      const flagY = floorY - 10;

      // Campfire sits at flagX - 9, height 6 (bottom line is logs 222222)
      const fireX = this.flagPos.x - 9;
      const fireY = floorY - 6;

      // Warm radial flickering light glow from the campfire
      const now = performance.now();
      const glowR = 24 + Math.sin(now * 0.007) * 3;
      const fireGlow = ctx.createRadialGradient(fireX + 5, fireY + 2, 2, fireX + 5, fireY + 2, glowR);
      fireGlow.addColorStop(0, 'rgba(255, 175, 55, 0.42)');
      fireGlow.addColorStop(0.45, 'rgba(255, 100, 30, 0.18)');
      fireGlow.addColorStop(1, 'rgba(255, 60, 0, 0)');
      ctx.fillStyle = fireGlow;
      ctx.beginPath();
      ctx.arc(fireX + 5, fireY + 2, glowR, 0, Math.PI * 2);
      ctx.fill();

      // Stone hearth base under campfire so it never floats
      ctx.fillStyle = p.getColor(1);
      ctx.fillRect(fireX, floorY - 1, 10, 2);
      ctx.fillStyle = p.getColor(2);
      ctx.fillRect(fireX + 1, floorY, 8, 1);

      // Stone base under flagpole
      ctx.fillStyle = p.getColor(1);
      ctx.fillRect(flagX - 1, floorY - 1, 6, 2);

      // Animated Campfire (3 frames cycling smoothly at ~10 FPS)
      const fireFrame = Math.floor((now / 95) % SPRITES.fire.length);
      drawSprite(ctx, SPRITES.fire[fireFrame], fireX, fireY, palette);

      // Animated Waving Flag (3 waving frames cycling with wind speed)
      const flagFrame = Math.floor((now / 140) % SPRITES.flag.length);
      drawSprite(ctx, SPRITES.flag[flagFrame], flagX, flagY, palette);

      // Golden Finial ball at top of flagpole
      ctx.fillStyle = '#ffd166';
      ctx.fillRect(flagX, flagY - 2, 2, 2);
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(flagX, flagY - 2, 1, 1);
    }

    // 11. Exit Door / Gateway Arch (Aligned, authentic pixel art)
    if (this.exitArea) {
      const dx = this.exitArea.x;
      const dy = this.exitArea.y;
      const dw = this.exitArea.w;
      const dh = this.exitArea.h;

      // Outer stone portal arch
      ctx.fillStyle = p.getColor(1);
      ctx.fillRect(dx, dy, dw, dh);
      ctx.fillStyle = p.getColor(3);
      ctx.fillRect(dx + 1, dy + 1, dw - 2, dh - 1);

      // Inner glowing doorway void
      ctx.fillStyle = '#000000';
      ctx.fillRect(dx + 2, dy + 3, dw - 4, dh - 3);

      // Shimmering mystical portal aura (pulsing colors 6 & 8)
      const t = performance.now() * 0.005;
      const glowCol = Math.sin(t) > 0 ? p.getColor(6) : p.getColor(8);
      ctx.fillStyle = glowCol;
      ctx.fillRect(dx + 3, dy + 4, dw - 6, dh - 5);

      // White portal core light
      ctx.fillStyle = '#ffffff';
      ctx.fillRect(dx + 4, dy + 6, dw - 8, dh - 9);

      // Top stone keystone & lantern
      ctx.fillStyle = p.getColor(4);
      ctx.fillRect(dx + 4, dy - 2, 4, 3);
      ctx.fillStyle = Math.sin(t * 2) > 0 ? '#ffffff' : p.getColor(8);
      ctx.fillRect(dx + 5, dy - 1, 2, 2);
    }

    // 12. Wind Streaks
    if (this.wind !== 0) {
      ctx.fillStyle = '#ffffff';
      ctx.globalAlpha = 0.35;
      for (const wp of this.windParticles) {
        ctx.fillRect(Math.round(wp.x), Math.round(wp.y), wp.len, 1);
      }
      ctx.globalAlpha = 1.0;
    }
  }
}

// Calculate the exact total number of strawberries across all 40 campaign rooms
export function getTotalStrawberries() {
  return LEVEL_DATA.reduce((sum, lvl) => {
    return sum + lvl.map.reduce((rSum, r) => rSum + (r.split('*').length - 1), 0);
  }, 0);
}
