export function drawPixelText(ctx, text, x, y, color, scale = 1) {
  const upper = text.toUpperCase();
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);

  for (let i = 0; i < upper.length; i++) {
    const char = upper[i];
    if (char === '\n') {
      // Not handling multiline here
      continue;
    }
    const cols = FONT_MAP[char] || FONT_MAP['?'];
    for (let c = 0; c < 5; c++) {
      const byte = cols[c] || 0;
      for (let r = 0; r < 7; r++) {
        if ((byte >> r) & 1) {
          ctx.fillRect(cx + c * scale, cy + r * scale, scale, scale);
        }
      }
    }
    cx += 6 * scale; // 5 cols + 1 spacing
  }
}

export function measurePixelText(text, scale = 1) {
  return text.length * 6 * scale;
}
