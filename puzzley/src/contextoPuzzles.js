export function getContextoRank(target, guess) {
  let t = '';
  let game = null;
  if (typeof target === 'string') {
    t = target.toUpperCase().trim();
    game = CONTEXTO_GAMES.find(item => (item.word || item.target) === t);
  } else if (target && typeof target === 'object') {
    t = (target.word || target.target || '').toUpperCase().trim();
    game = target;
  }
  const g = (guess || '').toUpperCase().trim();

  if (!t || !g) return 10000;
  if (t === g) return 1;

  const topList = game ? (game.topWords || game.ranked || []) : [];

  // 1. Direct match in curated semantic top list
  const idx = topList.findIndex(w => w.toUpperCase() === g);
  if (idx !== -1) {
    return idx + 2;
  }

  // 2. Morphological stemming & plural/inflection normalization
  const suffixes = ['ING', 'EST', 'ERS', 'ER', 'ED', 'ES', 'S', 'Y', 'LY'];
  for (const suf of suffixes) {
    if (g.length > suf.length + 2 && g.endsWith(suf)) {
      const stem = g.slice(0, -suf.length);
      if (stem === t) return 2;
      const sIdx = topList.findIndex(w => w.toUpperCase() === stem);
      if (sIdx !== -1) {
        return sIdx + 3;
      }
      if (suf === 'ING' || suf === 'ED' || suf === 'ER') {
        const stemE = stem + 'E';
        if (stemE === t) return 2;
        const seIdx = topList.findIndex(w => w.toUpperCase() === stemE);
        if (seIdx !== -1) {
          return seIdx + 3;
        }
      }
    }
  }

  // 3. Compound match (e.g. guess CAMPFIRE contains known top word CAMP)
  for (let i = 0; i < topList.length; i++) {
    const tw = topList[i].toUpperCase();
    if (tw.length >= 4 && g.length > tw.length && g.includes(tw)) {
      return i + 4;
    }
  }

  // 4. Deterministic semantic distance hash without orthographic letter-overlap bias
  // This guarantees unrelated words (like FLOOR or FIGHT for FIRE) remain strictly in the cold red tier (3,500 - 18,000)
  let hash = 0;
  for (let i = 0; i < g.length; i++) {
    hash = (hash * 37 + g.charCodeAt(i)) % 10007;
  }
  for (let i = 0; i < t.length; i++) {
    hash = (hash * 23 + t.charCodeAt(i)) % 10007;
  }

  let baseRank = 3500 + (hash % 12500);
  return baseRank;
}
